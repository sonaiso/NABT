"""Exact, source-bound *shape candidates* for a finite Lean pattern registry.

No root list, content-word policy, supplied category, or first-match choice is
used by the inverse reader. Every proposed root must refill its whole pattern
to the observed stem. Literal positions, repeated radicals, character order,
and the separately retained boundary must all agree exactly. A recovered
formal root is not an attested etymological root, an acquired word kind, or a
license to transfer a noun meaning, verb paradigm, syntactic role, or case.
"""

from copy import deepcopy
from hashlib import sha256
from importlib.resources import files
import json

from .errors import NabtError, natural, resource_limit
from .text_ir import span_dict
from .word_reader import _clusters, _scan, _source, _span

LAW_ID = "nabt.derivation-patterns.v1"
ALPHABET_ID = "nabt.arabic-radicals28.v1"
LANGUAGE_ID = "nabt.arabic-derivation-candidates.v1"
READER_VERSION = "nabt.derivation-reader.v1"
NUMBER_DOMAIN = "nabt.derivation.canonical-json-utf8.sentinel256.v1"
EXPECTED_TABLE_SHA256 = "0b4d6673c033955490468ad595fc1e988890bba282101e81a80580d3fc1fbf2f"
RADICALS = "بتثجحخدذرزسشصضطظعغفقكلمنهويء"
PROFILES = ("stem_exact_v1", "surface_v1")
MAX_SOURCE_BYTES = 8192
MAX_REPORT_BYTES = 4 * 1024 * 1024
MAX_CANDIDATES_PER_RUN = 256
MAX_OCCURRENCES = 128
_BOUNDARIES = frozenset("ٌٍَُِْ")


def _wire(value):
    try:
        raw = json.dumps(value, ensure_ascii=False, sort_keys=True,
                         separators=(",", ":"), allow_nan=False).encode("utf-8", "strict")
    except (TypeError, ValueError, UnicodeError, RecursionError) as error:
        raise NabtError("INVALID_DERIVATION_REPORT", "Use bounded strict JSON") from error
    if len(raw) > MAX_REPORT_BYTES:
        raise resource_limit("Derivation report exceeds its byte budget")
    return raw


def _id(value):
    return sha256(_wire(value)).hexdigest()


def installed_registry():
    """Replay installed, Lean-generated bytes; a caller cannot add templates."""
    try:
        raw = files("nabt").joinpath("data/derivation_patterns.json").read_bytes()
        if sha256(raw).hexdigest() != EXPECTED_TABLE_SHA256:
            raise ValueError("pattern registry pin differs")
        registry = json.loads(raw)
        if (registry["law_id"] != LAW_ID or registry["alphabet_id"] != ALPHABET_ID
                or registry["profile"] != "stem_exact_v1"):
            raise ValueError("pattern registry domain differs")
        patterns = registry["patterns"]
        if type(patterns) is not list or not 1 <= len(patterns) <= 128:
            raise ValueError("invalid pattern inventory")
        ids = []
        for pattern in patterns:
            ids.append(pattern["id"])
            arity, tokens = pattern["arity"], pattern["tokens"]
            if type(arity) is not int or not 1 <= arity <= 4 or type(tokens) is not list:
                raise ValueError("invalid typed template")
            if not 1 <= len(tokens) <= 48:
                raise ValueError("invalid template length")
            for token in tokens:
                if not (type(token) is int and 0 <= token < arity
                        or type(token) is str and len(token) == 1):
                    raise ValueError("invalid template symbol")
            if {t for t in tokens if type(t) is int} != set(range(arity)):
                raise ValueError("template does not witness every radical")
            if (type(pattern["endings"]) is not list
                    or any(type(e) is not str or e not in _BOUNDARIES for e in pattern["endings"])):
                raise ValueError("unrecognized boundary profile")
            if pattern["root_domain"] not in {"radicals28_shape_only", "sound_triliteral_distinct"}:
                raise ValueError("unrecognized root domain")
        if any(type(i) is not str or not i for i in ids) or len(set(ids)) != len(ids):
            raise ValueError("pattern identities must be unique")
        return registry
    except (OSError, KeyError, TypeError, ValueError, UnicodeError) as error:
        raise NabtError("INSTALLED_CONTRACT_FAILED", "Installed derivation law cannot be replayed",
                        status="DEFER") from error


def pattern_catalog():
    """Return the complete installed catalog without giving it lexical force."""
    return {"law_id": LAW_ID, "table_sha256": EXPECTED_TABLE_SHA256,
            "alphabet_id": ALPHABET_ID, "radicals": RADICALS,
            "patterns": installed_registry()["patterns"],
            "profiles": list(PROFILES), "future_pattern": None,
            "authority": "FINITE_FORMAL_SHAPES_NOT_ATTESTED_WORD_CLASSES"}


def _root_ok(root, pattern):
    if (type(root) is not str or len(root) != pattern["arity"]
            or any(c not in RADICALS for c in root)):
        return False
    if pattern["root_domain"] == "sound_triliteral_distinct":
        return not set(root) & set("وءي") and root[1] != root[2]
    return True


def _fill(pattern, root):
    return "".join(root[token] if type(token) is int else token for token in pattern["tokens"])


def _recover(pattern, stem):
    # First occurrences propose a root; only whole-template refill licenses a
    # match. In particular, the upstream Ishtiqaq.extract's skipped literal
    # positions are not treated as a recognizer.
    if len(stem) != len(pattern["tokens"]):
        return None
    proposed = [None] * pattern["arity"]
    for token, char in zip(pattern["tokens"], stem):
        if type(token) is int and proposed[token] is None:
            proposed[token] = char
    if any(c is None for c in proposed):
        return None
    root = "".join(proposed)
    if not _root_ok(root, pattern) or _fill(pattern, root) != stem:
        return None
    return root


def generate_derivation(root, pattern_id, *, ending=""):
    """Fill a named pattern. Supplied root and pattern remain explicit inputs."""
    if type(pattern_id) is not str or type(ending) is not str:
        raise NabtError("INVALID_DERIVATION_INPUT", "Use a named pattern and literal ending")
    pattern = next((p for p in installed_registry()["patterns"] if p["id"] == pattern_id), None)
    if pattern is None:
        raise NabtError("UNKNOWN_DERIVATION_PATTERN", "Pattern is outside the installed finite inventory", status="DEFER")
    if not _root_ok(root, pattern):
        raise NabtError("ROOT_OUTSIDE_PATTERN_DOMAIN", "Root must meet this pattern's explicit radical domain",
                        details={"alphabet_id": ALPHABET_ID, "root_domain": pattern["root_domain"],
                                 "arity": pattern["arity"]})
    if ending and ending not in pattern["endings"]:
        raise NabtError("UNSUPPORTED_DERIVATION_BOUNDARY", "Ending is outside this unsuffixed boundary profile", status="DEFER")
    stem = _fill(pattern, root)
    return {"law_id": LAW_ID, "table_sha256": EXPECTED_TABLE_SHA256,
            "alphabet_id": ALPHABET_ID, "pattern_id": pattern_id,
            "root": root, "root_basis": "SUPPLIED_FORMAL_RADICALS", "stem": stem,
            "boundary": ending, "surface": stem + ending,
            "source_contract": pattern["source_contract"],
            "status": "GENERATED_SHAPE", "attested_word": False,
            "attested_root": False, "semantic_projection": "NONE",
            "authority": "EXACT_TEMPLATE_FILL_ONLY"}


def _candidate(source, occurrence, pattern, stem, boundary, root, scope):
    offsets = [occurrence["span"]["start"]]
    for char in stem:
        offsets.append(offsets[-1] + len(char.encode("utf-8")))
    alignment, nuns = [], []
    for index, token in enumerate(pattern["tokens"]):
        symbol = {"type": "radical", "root_index": token} if type(token) is int else {
            "type": "literal", "literal": token}
        entry = {"pattern_position": index, **symbol, "surface": stem[index],
                 "span": span_dict(_span(source, offsets[index], offsets[index + 1]))}
        alignment.append(entry)
        if stem[index] == "ن":
            nuns.append({"span": entry["span"], "pattern_position": index,
                         "structural_origin": symbol, "grammatical_nun_type": None,
                         "authority": "TEMPLATE_POSITION_ONLY"})
    stem_span = span_dict(_span(source, offsets[0], offsets[-1]))
    boundary_span = None if not boundary else span_dict(_span(
        source, offsets[-1], occurrence["span"]["end"]))
    result = {"pattern_id": pattern["id"], "pattern_label": pattern["label"],
              "root": root, "root_status": "FORMAL_CANDIDATE_NOT_ATTESTED",
              "root_domain": pattern["root_domain"], "family": pattern["family"],
              "form": pattern["form"], "voice": pattern["voice"],
              "augmentation": pattern["augmentation"],
              "source_contract": pattern["source_contract"], "source_kind": pattern["source_kind"],
              "stem": stem, "boundary": boundary, "surface": occurrence["surface"],
              "stem_span": stem_span, "boundary_span": boundary_span,
              "alignment": alignment, "nun_positions": nuns,
              "reconstruction": "EXACT_UTF8_EQUALITY", "scope": scope,
              "occurrence_id": occurrence["occurrence_id"],
              "boundary_authority": "RETAINED_MARK_NOT_CASE_OR_MOOD",
              "lexical_class_activated": False, "actual_role": None, "actual_case": None,
              "authority": "FORMAL_PATTERN_MATCH_ONLY"}
    result["candidate_id"] = _id(result)
    return result


def _future_proposals(partition, occurrences):
    by_index = {o["partition_index"]: o for o in occurrences if o["reading_context"] == "UNQUOTED"}
    proposals = []
    for index, marker in by_index.items():
        if marker["surface"] != "سَوْفَ" or index + 2 not in by_index:
            continue
        gap = partition[index + 1]
        if gap["kind"] != "spacing" or any(c in gap["surface"] for c in "\r\n\u2028\u2029"):
            continue
        target = by_index[index + 2]
        item = {"marker_occurrence_id": marker["occurrence_id"],
                "target_occurrence_id": target["occurrence_id"],
                "marker_span": marker["span"], "target_span": target["span"],
                "imperfect_shape_candidates": [c["candidate_id"] for c in target["candidates"]
                                                if c["form"] == "imperfect"],
                "status": "CANDIDATE", "future_weight": None, "temporal_reading_activated": False,
                "actual_tense": None, "actual_role": None, "actual_case": None,
                "missing": ["INDEPENDENT_VERB_READING", "ACTIVATED_MARKER_AND_ATTACHMENT"],
                "source_contract": "Istiqama.awqatFil; ISTIQAMA_FEATURES_ARE_INPUT",
                "authority": "ADJACENCY_PROPOSAL_NOT_A_FUTURE_PATTERN"}
        item["proposal_id"] = _id(item)
        proposals.append(item)
    return proposals


def _written_runs(source, partition, scope):
    """Inspect quoted shape mentions without treating them as sentence uses.

    The outer partition remains unchanged. Child spans are rebuilt against
    the original source, never against the temporary inner scan's hash.
    Nested quote fragments unsupported by the existing scanner stay opaque.
    """
    for index, segment in enumerate(partition):
        if segment["kind"] == "written_run":
            yield index, {**deepcopy(segment), "reading_context": "UNQUOTED", "quotation_span": None}
        elif segment["kind"] == "quotation" and len(segment["surface"]) > 2:
            inner = segment["surface"][1:-1]
            if not inner:
                continue
            start = segment["span"]["start"] + len(segment["surface"][0].encode("utf-8"))
            try:
                children = _scan(_source(inner, source.source_id, scope))
            except NabtError as error:
                if error.code != "UNTERMINATED_QUOTE":
                    raise
                continue
            for child in children:
                if child["kind"] != "written_run":
                    continue
                span = child["span"]
                yield index, {"kind": "written_run", "surface": child["surface"],
                    "span": span_dict(_span(source, start + span["start"], start + span["end"])),
                    "reading_context": "MENTION", "quotation_span": deepcopy(segment["span"])}


def read_derivation(text, *, source_id="input", scope="default", profile="surface_v1"):
    if type(profile) is not str or profile not in PROFILES:
        raise NabtError("UNKNOWN_DERIVATION_PROFILE", "Choose an explicitly versioned exact profile")
    registry = installed_registry()
    source = _source(text, source_id, scope)
    partition = _scan(source)
    occurrences = []
    for index, segment in _written_runs(source, partition, scope):
        if len(occurrences) >= MAX_OCCURRENCES:
            raise resource_limit("Too many quoted or unquoted written runs", maximum=MAX_OCCURRENCES)
        run = deepcopy(segment)
        run.update(partition_index=index, occurrence_id=_id({"span": run["span"], "scope": scope}))
        surface = run["surface"]
        blockers = []
        try:
            clusters = _clusters(surface)
        except NabtError as error:
            if error.status == "REJECT":
                raise
            blockers.append({"code": error.code, "status": error.status, "span": run["span"]})
            clusters = []
        candidates = []
        if not blockers:
            for pattern in registry["patterns"]:
                alternatives = [(surface, "")]
                if profile == "surface_v1" and surface[-1:] in pattern["endings"]:
                    alternatives.append((surface[:-1], surface[-1:]))
                for stem, boundary in alternatives:
                    root = _recover(pattern, stem)
                    if root is not None:
                        candidates.append(_candidate(source, run, pattern, stem, boundary, root, scope))
        if len(candidates) > MAX_CANDIDATES_PER_RUN:
            raise resource_limit("Too many pattern alternatives", maximum=MAX_CANDIDATES_PER_RUN)
        candidates.sort(key=lambda c: (c["pattern_id"], c["root"], c["boundary"]))
        roots = sorted({c["root"] for c in candidates})
        pattern_ids = sorted({c["pattern_id"] for c in candidates})
        run.update(candidates=candidates, blockers=blockers,
            shape_status="NO_MATCH_IN_PROFILE" if not candidates else "UNIQUE_IN_PROFILE" if len(candidates) == 1 else "AMBIGUOUS",
            # Overall linguistic authority stays deferred even for one shape.
            status="DEFER", actual_role=None, actual_case=None,
            axes={"formal_root": {"status": "CANDIDATE" if roots else "DEFER", "candidates": roots},
                  "pattern": {"status": "CANDIDATE" if pattern_ids else "DEFER", "candidates": pattern_ids},
                  "attested_root": {"status": "DEFER", "candidates": [], "missing": ["INDEPENDENT_LEXICAL_ROOT_WITNESS"]},
                  "kind": {"status": "DEFER", "candidates": ["noun", "verb", "particle"]},
                  "nominal_semantics": {"status": "DEFER", "candidates": ["jamid", "mushtaq"]},
                  "verb_productivity": {"status": "DEFER", "candidates": ["jamid", "partial", "full"],
                                        "missing": ["SAME_LEXEME_PARADIGM_AVAILABILITY_WITNESSES"]}},
            segmentation={"status": "EXACT_WRITTEN_RUN_PARTITION", "grammatical_segmentation": None,
                          "nun_type": None, "attachment": None},
            final_nun_observed=bool(clusters and clusters[-1][0] == "ن"),
            missing=["LEXICAL_ROOT_AND_FORM_ATTESTATION", "GRAMMATICAL_SEGMENTATION_AND_ATTACHMENT"],
            authority="CANDIDATE_SET_NOT_LEXICAL_CLASSIFICATION")
        occurrences.append(run)
    restored = "".join(p["surface"] for p in partition).encode("utf-8") == source.raw_bytes
    if not restored:
        raise NabtError("INTERNAL_CONTRACT_FAILED", "Partition did not restore source")
    report = {"language_id": LANGUAGE_ID, "reader_version": READER_VERSION,
              "law_id": LAW_ID, "table_sha256": EXPECTED_TABLE_SHA256, "alphabet_id": ALPHABET_ID,
              "profile": profile, "source_id": source.source_id, "source_sha256": source.sha256,
              "scope": scope, "raw_text": source.raw_bytes.decode("utf-8"),
              "partition": partition, "occurrences": occurrences,
              "future_proposals": _future_proposals(partition, occurrences),
              "source_restored": restored, "status": "DEFER", "facts": [],
              "recognition_basis": {"content_word_answer_entries_used": 0, "given_root_list_used": False,
                                    "given_class_used": False, "unicode_normalization": "NONE",
                                    "whole_template_refill_required": True,
                                    "pattern_count": len(registry["patterns"])},
              "semantic_projection": "NONE", "world_truth": "NOT_ESTABLISHED",
              "unimplemented_axes": ["ATTESTED_ETYMOLOGICAL_ROOT", "WEAK_AND_HAMZA_REALIZATION",
                                     "CLITIC_AND_NUN_ATTACHMENT", "ROLE_AND_CASE_FROM_NEW_TEXT",
                                     "RECURSIVE_NESTED_QUOTATION_ANALYSIS"],
              "authority": "REPLAYED_EXACT_PATTERN_CANDIDATES"}
    _wire(report)
    return report


def verify_derivation(report, *, text=None, source_id=None, scope=None, profile=None):
    try:
        if type(report) is not dict:
            raise ValueError("not a report")
        fresh = read_derivation(report["raw_text"] if text is None else text,
            source_id=report["source_id"] if source_id is None else source_id,
            scope=report["scope"] if scope is None else scope,
            profile=report["profile"] if profile is None else profile)
        if _wire(report) != _wire(fresh):
            raise ValueError("report differs from replay")
        return {"valid": True, "status": "VERIFIED", "source_sha256": fresh["source_sha256"],
                "authority": "SOURCE_BOUND_PATTERN_REPORT_REPLAY_ONLY"}
    except (OSError, KeyError, TypeError, ValueError, RecursionError) as error:
        if isinstance(error, NabtError) and error.status == "DEFER":
            return {"valid": False, "status": "DEFER", "code": error.code}
        return {"valid": False, "status": "REJECT", "code": "INVALID_DERIVATION_REPORT"}


def derivation_number(report):
    check = verify_derivation(report)
    if not check["valid"]:
        raise NabtError(check["code"], "Derivation report cannot be encoded", status=check["status"])
    return int.from_bytes(b"\x01" + _wire(report), "big")


def decode_derivation(number):
    natural(number, "derivation_number")
    if number.bit_length() > 8 * (MAX_REPORT_BYTES + 1):
        raise resource_limit("Derivation number exceeds its byte budget")
    try:
        raw = number.to_bytes((number.bit_length() + 7) // 8, "big")
        if not raw.startswith(b"\x01"):
            raise ValueError("missing sentinel")
        report = json.loads(raw[1:].decode("utf-8"))
        if b"\x01" + _wire(report) != raw or not verify_derivation(report)["valid"]:
            raise ValueError("noncanonical or unreplayed report")
        return report
    except (ValueError, UnicodeError, RecursionError) as error:
        if isinstance(error, NabtError):
            raise
        raise NabtError("INVALID_DERIVATION_NUMBER", "Number is not a canonical replayed derivation report") from error
