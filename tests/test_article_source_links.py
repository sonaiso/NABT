NAMES = ["Nabt.AlignedAcquisitionV2." + name for name in (
    "acquire_spans", "acquire_restores_source", "acquire_offsets_contiguous",
    "acquired_no_pending", "verified_binding", "licensed_override_has_finite_witness",
    "article_onset_cells", "connected_no_handoff", "checkedHandoff_sound",
    "silent_initial_rejected",
)]


def compiled_fixture(root: Path, names: list[str] | None = None) -> dict:
    """Small synthetic tree with no real Lean proofs; only index checks apply."""
    names = list(NAMES if names is None else names)
    files = {
        "formal/Nabt/AlignedAcquisitionV2.lean": "-- synthetic source; no kernel evidence\n",
        "formal/ExportProofCatalog.lean": "-- synthetic exporter\n",
        "formal/theorems.json": json.dumps({"theorems": names}) + "\n",
        "formal/lean-toolchain": "synthetic-test-toolchain\n",
        "tools/proof_catalog.py": "# synthetic catalogue source\n",
    }
    for relative, contents in files.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents, encoding="utf-8")
    hashes = {path: sha256(contents.encode()).hexdigest() for path, contents in files.items()}
    rows = [{
        "name": name, "canonical_name": name, "module": "Nabt.AlignedAcquisitionV2",
        "statement_sha256": sha256(("synthetic statement " + name).encode()).hexdigest(),
        "source_path": "formal/Nabt/AlignedAcquisitionV2.lean",
        "source_sha256": hashes["formal/Nabt/AlignedAcquisitionV2.lean"],
        "universe_parameters": 0, "proof_dependencies": [], "type_dependencies": [], "axioms": [],
    } for name in names]
    return {"schema": "nabt.compiled-proof-catalog.v1", "authority": "COMPILED_DECLARATION_INDEX_ONLY",
            "inputs": hashes, "lean_toolchain": "synthetic-test-toolchain", "theorems": rows}


class ArticleSourcePayloadTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.source = json.loads((links.ROOT / links.SOURCE_PATH).read_text())

    def test_retained_sources_and_all_sixteen_spans_match(self):
        index = links._validate_source_payload(links.ROOT, self.source)
        self.assertEqual(set(index["sources"]), {"qatr", "sibawayhi", "mukhtar_sihah"})
        self.assertEqual(len(index["passages"]), 16)
        self.assertEqual(set(index["entries"]), {"ARTICLE_HAQQ", "ARTICLE_QAWM", "ARTICLE_GHULAM"})
        self.assertEqual(sha256((links.ROOT / links.SOURCE_PATH).read_bytes()).hexdigest(),
                         "d5d348e17fd3f34eaa69e5a031956972860dd8dbf3eee25674a265ee4578543c")

    def test_offsets_reject_boolean_negative_empty_and_past_end(self):
        mutations = [
            ("byte_start_0based", True), ("byte_start_0based", -1),
            ("byte_end_0based_exclusive", 0), ("byte_end_0based_exclusive", 10**20),
            ("line_start_1based", False), ("line_end_1based_inclusive", 10**20),
        ]
        for key, value in mutations:
            source = deepcopy(self.source)
            source["passages"][0][key] = value
            with self.subTest(key=key, value=value), self.assertRaisesRegex(links.LinkError, "offsets"):
                links._validate_source_payload(links.ROOT, source)

    def test_byte_line_boundary_mismatch_is_not_a_valid_substring(self):
        source = deepcopy(self.source)
        row = source["passages"][0]
        row["byte_start_0based"] += 1
        with self.assertRaisesRegex(links.LinkError, "byte/line offsets disagree"):
            links._validate_source_payload(links.ROOT, source)

    def test_raw_text_and_span_hash_are_independently_checked(self):
        for field, value in (("raw_text", "different source"), ("span_sha256", "0" * 64)):
            source = deepcopy(self.source)
            source["passages"][0][field] = value
            with self.subTest(field=field), self.assertRaises(links.LinkError):
                links._validate_source_payload(links.ROOT, source)

    def test_full_source_identity_and_path_cannot_be_replaced(self):
        for field, value in (("source_sha256", "0" * 64), ("repository_path", "../../source"),
                             ("runtime_required", 0), ("bytes", True)):
            source = deepcopy(self.source)
            source["sources"][0][field] = value
            with self.subTest(field=field), self.assertRaises(links.LinkError):
                links._validate_source_payload(links.ROOT, source)

    def test_repeated_or_missing_passage_is_rejected(self):
        for mutation in ("duplicate", "missing"):
            source = deepcopy(self.source)
            if mutation == "duplicate":
                source["passages"].append(deepcopy(source["passages"][0]))
            else:
                source["passages"].pop()
            with self.subTest(mutation=mutation), self.assertRaises(links.LinkError):
                links._validate_source_payload(links.ROOT, source)

    def test_authored_reading_guards_cannot_drop_waw_sukun_or_supply_missing_case(self):
        for mutation in ("waw", "case", "prefix", "onset", "entry"):
            source = deepcopy(self.source)
            registry = source["finite_registry"]
            if mutation == "waw":
                next(x for x in registry["entries"] if x["id"] == "ARTICLE_QAWM")["stem_pieces"][1]["allowed_marks"] = [""]
            elif mutation == "case":
                registry["terminal_ordinary_marks"].append("")
            elif mutation == "prefix":
                registry["prefix_pieces"][0]["allowed_marks"].append("ِ")
            elif mutation == "onset":
                registry["onset_interpretation"] = "connected"
            else:
                registry["entries"].append({"id": "ARTICLE_GENERIC", "stem_pieces": []})
            with self.subTest(mutation=mutation), self.assertRaises(links.LinkError):
                links._validate_source_payload(links.ROOT, source)

    def test_conventions_and_link_passages_must_remain_authored_and_resolved(self):
        for mutation in ("kind", "source", "duplicate"):
            source = deepcopy(self.source)
            row = source["conventions"][0]
            if mutation == "kind":
                row["evidence_kind"] = "SOURCE_PROVED"
            elif mutation == "source":
                row["passage_ids"] = ["invented_passage"]
            else:
                row["passage_ids"] *= 2
            with self.subTest(mutation=mutation), self.assertRaises(links.LinkError):
                links._validate_source_payload(links.ROOT, source)

    def test_public_source_reader_rejects_reformatted_or_modified_packet_before_loading_sources(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            target = root / links.SOURCE_PATH
            target.parent.mkdir(parents=True)
            target.write_text(json.dumps(self.source), encoding="utf-8")
            with self.assertRaisesRegex(links.LinkError, "packet pin differs"):
                links._read_source(root)


class ArticleCompiledLinkTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        source = json.loads((links.ROOT / links.SOURCE_PATH).read_text())
        cls.source_index = links._validate_source_payload(links.ROOT, source)

    def test_all_ten_explicit_names_link_and_claims_remain_bounded(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            compiled = compiled_fixture(root)
            declarations = links._validate_compiled(root, compiled)
            report = links._compose(self.source_index, compiled, declarations)
        self.assertEqual(report["referenced_declaration_names"], sorted(NAMES))
        self.assertEqual(report["counts"]["explicit_reference_edges"], 14)
        self.assertEqual(report["compiled_proof_catalog_sha256"], proof_catalog.digest(compiled))
        self.assertEqual({x["id"] for x in report["nodes"] if x["kind"] == "finite_reading"},
                         {"ARTICLE_HAQQ", "ARTICLE_QAWM", "ARTICLE_GHULAM"})
        for key in ("fresh_kernel_check_performed_by_this_command", "linguistic_interpretation_proved",
                    "python_lean_refinement_proved", "connected_pronunciation_implemented", "arabic_completeness_established"):
            self.assertIs(report["claims"][key], False)

    def test_stale_changed_added_removed_inputs_are_rejected(self):
        for mutation in ("changed", "added", "removed", "tooling"):
            with self.subTest(mutation=mutation), tempfile.TemporaryDirectory() as directory:
                root = Path(directory)
                compiled = compiled_fixture(root)
                if mutation == "changed":
                    (root / "formal/Nabt/AlignedAcquisitionV2.lean").write_text("changed")
                elif mutation == "added":
                    (root / "formal/New.lean").write_text("new imported premise")
                elif mutation == "removed":
                    del compiled["inputs"]["formal/ExportProofCatalog.lean"]
                else:
                    (root / "tools/proof_catalog.py").write_text("changed exporter semantics")
                with self.assertRaisesRegex(links.LinkError, "input inventory/hashes"):
                    links._validate_compiled(root, compiled)

    def test_build_cache_lean_files_are_not_false_new_inputs(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            compiled = compiled_fixture(root)
            cache = root / "formal/.lake/packages/Example.lean"
            cache.parent.mkdir(parents=True)
            cache.write_text("cached dependency")
            links._validate_compiled(root, compiled)

    def test_exact_manifest_sequence_rejects_reorder_duplicate_namespace_and_extra_name(self):
        for mutation in ("order", "duplicate", "namespace", "extra"):
            with self.subTest(mutation=mutation), tempfile.TemporaryDirectory() as directory:
                root = Path(directory)
                compiled = compiled_fixture(root)
                if mutation == "order":
                    compiled["theorems"].reverse()
                elif mutation == "duplicate":
                    compiled["theorems"].append(deepcopy(compiled["theorems"][0]))
                elif mutation == "namespace":
                    compiled["theorems"][0]["name"] = "Nabt.AlignedAcquisitionV2"
                else:
                    row = deepcopy(compiled["theorems"][0])
                    row["name"] += "_invented"
                    compiled["theorems"].append(row)
                with self.assertRaises(links.LinkError):
                    links._validate_compiled(root, compiled)

    def test_present_namespace_or_similar_name_does_not_satisfy_explicit_link(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            compiled = compiled_fixture(root, [n for n in NAMES if not n.endswith("article_onset_cells")]
                                         + ["Nabt.AlignedAcquisitionV2.article_onset_cells_unrelated"])
            declarations = links._validate_compiled(root, compiled)
            with self.assertRaisesRegex(links.LinkError, "explicit theorem missing"):
                links._compose(self.source_index, compiled, declarations)

    def test_unbound_source_bad_statement_and_false_canonical_identity_fail(self):
        for field, value in (("source_sha256", "0" * 64), ("source_path", "formal/Other.lean"),
                             ("statement_sha256", "not-a-hash"), ("canonical_name", NAMES[1]),
                             ("universe_parameters", True), ("axioms", ["invented_axiom"])):
            with self.subTest(field=field), tempfile.TemporaryDirectory() as directory:
                root = Path(directory)
                compiled = compiled_fixture(root)
                compiled["theorems"][0][field] = value
                with self.assertRaises(links.LinkError):
                    links._validate_compiled(root, compiled)


class ArticleSourceLinkJsonAndCliTests(unittest.TestCase):
    def test_strict_json_rejects_duplicate_keys_nonfinite_and_surrogates(self):
        for value in (b'{"a":1,"a":2}', b'{"a":{"x":1,"x":2}}', b'{"x":NaN}', b'"\\ud800"'):
            with self.subTest(value=value), self.assertRaises(ValueError):
                links._strict_json(value)

    def test_output_is_exclusive_and_check_uses_type_strict_full_report(self):
        report = {"counts": {"finite_readings": 3}, "claimed": False}
        with tempfile.TemporaryDirectory() as directory, patch.object(links, "build_report", return_value=report):
            path = Path(directory) / "links.json"
            with redirect_stdout(io.StringIO()):
                self.assertEqual(links.main(["--output", str(path)]), 0)
                original = path.read_bytes()
                self.assertEqual(links.main(["--output", str(path)]), 1)
                self.assertEqual(path.read_bytes(), original)
                self.assertEqual(links.main(["--check", str(path)]), 0)
                path.write_text(json.dumps({**report, "claimed": 0}))
                self.assertEqual(links.main(["--check", str(path)]), 1)

    def test_duplicate_keys_in_check_report_are_not_collapsed(self):
        report = {"counts": {"finite_readings": 3}}
        with tempfile.TemporaryDirectory() as directory, patch.object(links, "build_report", return_value=report):
            path = Path(directory) / "links.json"
            path.write_text('{"counts":{},"counts":{"finite_readings":3}}')
            with redirect_stdout(io.StringIO()):
                self.assertEqual(links.main(["--check", str(path)]), 1)


