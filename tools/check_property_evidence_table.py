#!/usr/bin/env python3
"""Compare the independent Lean finite-predicate ledger to Python bit arithmetic.

Input is generated by `lake env lean --run PropertyEvidenceTable.lean`.
Every R/P/N triple at width four must occur exactly once. This is a differential
check of 4,096 states, not a universal Python refinement proof or a language test.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from nabt.learning.source_evidence import (  # noqa: E402
    EvidenceLedger,
    evaluate_license,
)


def compare(raw: bytes) -> dict[str, object]:
    rows = csv.DictReader(io.StringIO(raw.decode("utf-8")), delimiter="\t")
    expected_columns = (
        "required",
        "positive",
        "negative",
        "status",
        "missing",
        "conflicts",
        "refutations",
    )
    if tuple(rows.fieldnames or ()) != expected_columns:
        raise ValueError("unexpected Lean table header")
    seen: set[tuple[int, int, int]] = set()
    counts: Counter[str] = Counter()

    def natural(value: str | None) -> int:
        if not isinstance(value, str) or re.fullmatch(r"0|[1-9][0-9]*", value) is None:
            raise ValueError("noncanonical natural number in Lean table")
        return int(value)

    for row in rows:
        if set(row) != set(expected_columns) or any(value is None for value in row.values()):
            raise ValueError("malformed Lean table row")
        r, p, n = (natural(row[key]) for key in expected_columns[:3])
        if not all(0 <= value < 16 for value in (r, p, n)):
            raise ValueError("Lean table value outside the declared width")
        if (r, p, n) in seen:
            raise ValueError(f"duplicate Lean table state: {(r, p, n)}")
        seen.add((r, p, n))
        result = evaluate_license(r, EvidenceLedger(4, p, n))
        actual = (result.status.value, result.missing, result.conflicts, result.negative)
        expected = (
            row["status"],
            natural(row["missing"]),
            natural(row["conflicts"]),
            natural(row["refutations"]),
        )
        if actual != expected:
            raise ValueError(f"ledger mismatch at {(r, p, n)}: {actual} != {expected}")
        counts[result.status.value] += 1
    if len(seen) != 16**3:
        raise ValueError("incomplete Lean table")
    return {
        "scope": "all required/positive/negative masks at width four",
        "states": len(seen),
        "mismatches": 0,
        "statuses": dict(sorted(counts.items())),
        "lean_table_sha256": hashlib.sha256(raw).hexdigest(),
        "formal_scope": "Lean specification theorems; Python checked on this finite domain",
        "linguistic_accuracy_measured": False,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("table", type=Path, nargs="?", help="optional saved Lean TSV; otherwise build and run Lean")
    parser.add_argument("--lake", default="lake")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    try:
        if args.table is None:
            subprocess.run(
                [args.lake, "build", "Nabt.PropertyEvidence"],
                cwd=ROOT / "formal",
                check=True,
            )
            result = subprocess.run(
                [args.lake, "env", "lean", "--run", "PropertyEvidenceTable.lean"],
                cwd=ROOT / "formal",
                check=True,
                capture_output=True,
            )
            raw = result.stdout
        else:
            raw = args.table.read_bytes()
        report = compare(raw)
        report["fresh_lean_export_compared"] = args.table is None
        report["module_build_checked"] = args.table is None
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        print(json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False))
        return 1
    text = json.dumps(report, ensure_ascii=False, indent=2) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
    print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
