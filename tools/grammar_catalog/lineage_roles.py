def prepare(atoms, add):
    rows = defaultdict(lambda: defaultdict(set))
    for pred, left, right in atoms:
        rows[pred][left].add(right)
    # Each check denotes one application. Different cases need different IDs.
    for pred in ("باب_الفحص","موضوع_الفحص","أصل_الفحص","فرع_الفحص","كل_الفحص","فارق_معتمد","نمط_عبور",
                 "وسط_عبور","مستند_الدور","واقعة_الدور","وجه_الدور","آلية_الفحص","قطب","شحنة","طرف_ثان","موضع_لفظ","قرينة_قراءة"):
        if any(len(values)>1 for values in rows[pred].values()):
            raise ValueError("Multiple assignments to one case coordinate: "+pred)
    edges = [(a,b) for relation in ("فرع_من","نوع") for a,values in rows[relation].items() for b in values]
    ancestors(edges,{x for edge in edges for x in edge})
    for k, first in rows["موضوع_الفحص"].items():
        for x in first:
            if x in rows["كل_الفحص"].get(k,()):
                raise ValueError("A proper part is distinct from its whole")
            for y in rows["طرف_ثان"].get(k,()):
                if x != y:
                    add(("طرفان_متميزان",k,y),(("موضوع_الفحص",k,x),("طرف_ثان",k,y)),"تغاير_المعينين")
    # Prevent cycles in asserted proper-part topology, even across separate checks.
    parts = [(x,y) for k,first in rows["موضوع_الفحص"].items() if "باب_جزئية" in rows["باب_الفحص"].get(k,())
             for x in first for y in rows["كل_الفحص"].get(k,())]
    ancestors(parts,{x for edge in parts for x in edge})
