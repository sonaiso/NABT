#!/usr/bin/env python3
"""Deterministically export the learned inert DAG for an independent Lean check.

The source data is not a proof. LearnedModel.lean proves the pointwise contract
of this exact artifact with the kernel; no Python-generated trust flag is read.
"""

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from nabt.acquisition import Leaf, acquire_transition_model


def export() -> str:
    result = acquire_transition_model()
    if result.model is None:
        raise RuntimeError("Acquisition did not close its finite contract")
    nodes = result.model.nodes
    lines = ["import Std", "", "/-! Generated by tools/export_learned_model.py; data, not a proof.",
             f"Model SHA-256: {result.model.verification.model_sha256}",
             "Input encoding: 128 * state + atom; state < 97, atom < 116.",
             "The final-state predicate is not learned.", "-/", "namespace Nabt.LearnedData", ""]
    for i, node in enumerate(nodes):
        if type(node) is Leaf:
            lines.append(f"def n{i} (_code : Nat) : Nat × Nat := ({node.target}, {node.weight})")
        else:
            lines.append(f"def n{i} (code : Nat) : Nat × Nat := if code.testBit {node.bit} then n{node.one} code else n{node.zero} code")
    lines.extend(["", f"def predict := n{len(nodes) - 1}", "", "end Nabt.LearnedData", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "formal" / "Nabt" / "LearnedModelData.lean"
    content = export()
    if args.check:
        if destination.read_text(encoding="utf-8") != content:
            raise SystemExit("Learned artifact differs from deterministic Python export")
        print("Learned artifact matches the complete deterministic DAG export")
    else:
        destination.write_text(content, encoding="utf-8")
        print(destination)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
