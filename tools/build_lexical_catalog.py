def citation(book,needle,sources):
    data,revision=sources[book]
    raw=needle.encode()
    if data.count(raw)!=1:
        raise ValueError(f'quotation must occur exactly once: {book} {needle}')
    start=data.index(raw)
    return {'work':book,'revision':revision,'source_sha256':digest(data),
            'start_byte':start,'end_byte':start+len(raw),'quotation':needle}

def build(lisan_path):
    lisan=fetch_lisan(lisan_path)
    maqayis=(ROOT/'evidence/classical_language/sources/maqayis.txt').read_bytes()
    if digest(maqayis)!=MAQAYIS_SHA:raise ValueError('Maqayis hash')
    s3=(ROOT/'evidence/mantuq_mafhum/sources/shakhsiyya3.txt').read_bytes()
    sources={'lisan':(lisan,LISAN_REV),'maqayis':(maqayis,MAQAYIS_REV),
             'shakhsiyya3':(s3,'user-supplied-2026-10-24-excerpt-v1')}
    rows=[]
    for book,name,root,quote,components in SELECTED:
        rows.append({'id':book+':'+name,'root':root,'citation':citation(book,quote,sources),
                     'components':components,'interpretation_status':'AUTHORED_NOT_INDEPENDENTLY_ADJUDICATED',
                     'scope':'author-proposed root origin' if name.endswith('-origin') else 'selected definition reading'})
    rules=[]
    for sense,target,quote in [
        ('lisan:asad-animal','الشجاعة','ك'+ 'دلالة الأسد على الشجاعة'),
        ('lisan:ama','البصر','كالعمى والبصر')]:
        rules.append({'sense_id':sense,'target':target,'kind':'mental',
                      'citation':citation('shakhsiyya3',quote,sources),
                      'alignment_status':'AUTHORED_CROSS_SOURCE_SENSE_ALIGNMENT',
                      'scope':'mental transition in this source theory, not an external predicate'})
    return {'schema':'nabt.lexical-denotation.catalog.v1','law_id':'nabt.lexical-denotation.v1',
      'authority':'CONDITIONAL_INTERPRETATION_ONLY','world_truth_measured':False,
      'all_arabic_senses_enumerated':False,'independent_semantic_adjudication':False,
      'senses':rows,'necessities':rules}

def lean(catalog):
    q=lambda s:json.dumps(s,ensure_ascii=False)
    def cit(c):
        return '⟨'+', '.join([q(c['work']),q(c['revision']),q(c['source_sha256']),str(c['start_byte']),str(c['end_byte']),q(c['quotation'])])+'⟩'
    lines=['import Nabt.LexicalDenotation','','-- Generated by tools/build_lexical_catalog.py; interpretations are explicit premises.',
           'namespace Nabt.LexicalCatalog','open LexicalDenotation']
    for i,s in enumerate(catalog['senses']):
        lines.append(f'def sense{i} : Sense := ⟨{q(s["id"])}, {q(s["root"])}, {cit(s["citation"])}, [{", ".join(map(q,s["components"]))}]⟩')
    lines.append('def senses : List Sense := ['+', '.join('sense'+str(i) for i in range(len(catalog['senses'])))+']')
    ids=[s['id'] for s in catalog['senses']]
    rules=['⟨sense'+str(ids.index(r['sense_id']))+', '+q(r['target'])+', .mental, '+cit(r['citation'])+'⟩' for r in catalog['necessities']]
    lines+=['def necessities : List Necessity := ['+', '.join(rules)+']',
      'def lookup (id : String) : Option Sense := senses.find? (fun s => s.id == id)',
      'def forRoot (root : String) : List Sense := senses.filter (fun s => s.root == root)',
      'theorem ids_unique : (senses.map Sense.id).Nodup := by decide',
      'theorem lisan_qalam_preserves_three : (forRoot "قلم").length = 3 := by decide',
      'theorem fahm_source_definitions_not_identical : sense0.components ≠ sense12.components := by decide',
      'theorem single_gloss_has_no_word_parts : check necessities sense0 .inclusion ["القلب"] = false := by decide',
      'theorem blindness_does_not_assert_sight : check necessities sense11 .entailment ["البصر"] = true ∧ check necessities sense11 .inclusion ["البصر"] = false := by decide',
      'theorem maqayis_origin_inclusion : check necessities sense13 .inclusion ["المأوى"] = true := by decide',
      'theorem whole_is_not_proper_part : check necessities sense13 .inclusion sense13.components = false := by decide',
      'theorem unrelated_root_rejected : check necessities sense2 .matching sense8.components = false := by decide',
      'end Nabt.LexicalCatalog','']
    return '\n'.join(lines)

